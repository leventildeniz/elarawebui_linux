type Key = keyof typeof dict.en;
// English-only — Turkish UI removed by operator decision. Backend still accepts
// Turkish UTF-8 content (chat, model I/O); only the UI layer is locked to EN.
export const LOCALES: { code: Locale; label: string }[] = [
  { code: "en", label: "English" },
];

const Ctx = createContext<{ locale: Locale; setLocale: (l: Locale) => void; t: (k: Key) => string }>({
  locale: "en", setLocale: () => {}, t: (k) => k,
});

export function I18nProvider({ children }: { children: ReactNode }) {
  // Locale is permanently "en". setLocale kept as no-op for backward compat with
  // any caller that still references it; LOCALES carries only the EN entry.
  const locale: Locale = "en";
  const setLocale = (_: Locale) => {};
  const t = (k: Key) => (dict.en as Record<string, string>)[k] || k;
  useEffect(() => {
    if (typeof window === "undefined") return;
    try { localStorage.setItem("locale", "en"); } catch {}
  }, []);
  return <Ctx.Provider value={{ locale, setLocale, t }}>{children}</Ctx.Provider>;
}

export const useI18n = () => useContext(Ctx);
